// Reference values generated with jax.lax and jax.jvp on CPU (JAX 0.12.0.1).

use gnx_expr::pass::Builder;
use gnx_expr::{Op, Value, VarInfo};
use gnx_math::ops::{dtype, elementwise, special};
use gnx_math::{ArrayInfo, DType, DataHandle, ExecOpts, HostBuffer, Shape, TransferPolicy};
use gnx_xla::XlaDevice;

fn info(dtype: DType) -> VarInfo {
    VarInfo::new(ArrayInfo::new(Shape::fixed([3]), dtype))
}

fn input(values: &[f32; 3]) -> Value {
    let metadata = ArrayInfo::new(Shape::fixed([3]), DType::F32);
    let bytes: Vec<_> = values.iter().flat_map(|v| v.to_le_bytes()).collect();
    Value::new(DataHandle::new(
        HostBuffer::copy_from_slice(metadata, &bytes).unwrap(),
    ))
}

fn close(actual: &[u8], expected: &[f32; 3], operation: &str) {
    assert_eq!(actual.len(), 12, "{operation}");
    let actual = actual
        .chunks_exact(4)
        .map(|v| f32::from_le_bytes(v.try_into().unwrap()));
    for (a, &e) in actual.zip(expected) {
        assert!(
            (a - e).abs() <= 1e-4 * (1. + e.abs()),
            "{operation}: {a} vs {e}"
        );
    }
}

fn check(
    device: &XlaDevice,
    op: Op,
    args: &[[f32; 3]],
    ty: DType,
    expected: [f32; 3],
    derivative: Option<[f32; 3]>,
) {
    let name = op.to_string();
    let mut b = Builder::new();
    let primals: Vec<_> = args.iter().map(|_| b.input(info(DType::F32))).collect();
    let y = b.emit1(op, &primals, info(ty));
    let body = b.finish(vec![y]);
    let mut arguments: Vec<_> = args.iter().map(input).collect();
    let program = if derivative.is_some() {
        use gnx_expr::SubExprBuilder;
        let mut b = Builder::new();
        let input: Vec<_> = (0..2 * args.len())
            .map(|_| b.input(info(DType::F32)))
            .collect();
        let wrt: Vec<_> = (0..args.len()).collect();
        let result = b.emit(
            gnx_transforms::ops::ad::jvp(&wrt, &[0]),
            &input,
            [info(ty), info(ty)],
            vec![SubExprBuilder::new(body)],
        );
        arguments.extend(args.iter().map(|_| self::input(&[1.; 3])));
        b.finish(result)
    } else {
        body
    };
    let result = device
        .compile(&program.build().unwrap())
        .unwrap_or_else(|e| panic!("{name}: {e}"))
        .run(
            &arguments,
            ExecOpts {
                transfers: TransferPolicy::AllowCopy,
            },
        )
        .unwrap();
    let actual = device
        .download(result[0].downcast::<DataHandle>().unwrap())
        .unwrap();
    if ty == DType::Bool {
        assert_eq!(actual.bytes(), expected.map(|v| v as u8), "{name}");
    } else {
        close(actual.bytes(), &expected, &name);
    }
    if let Some(tangent) = derivative {
        let actual = device
            .download(result[1].downcast::<DataHandle>().unwrap())
            .unwrap();
        close(actual.bytes(), &tangent, &format!("{name} JVP"));
    }
}

